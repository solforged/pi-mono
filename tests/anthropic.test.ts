const identity = "You are Claude Code, Anthropic's official CLI for Claude.";
const fingerprint = { sessionId: "test-session", deviceId: "a".repeat(64) };
function body(overrides: Record<string, unknown> = {}) {
  return JSON.stringify({
    model: "claude-opus-5-5", messages: [{ role: "user", content: "Hello from a Unicode prompt: 🦊" }],
    system: [{ type: "text", text: identity, cache_control: { type: "ephemeral" } }, { type: "text", text: "Keep it short." }],
    max_tokens: 128000, stream: true, ...overrides,
  });
}
function request(overrides: RequestInit = {}, url = "https://api.anthropic.com/v1/messages?beta=true") {
  return new Request(url, {
    method: "POST", body: body(),
    headers: { authorization: "Bearer sk-ant-oat-test", "content-type": "application/json" }, ...overrides,
  });
}
function rejection(version = "2.1.300", status = 400) {
  return new Response(JSON.stringify({ error: { type: "claude_code_version_too_old", message: `Claude Code version ${version} or newer is required` } }), { status });
}
async function capture(input: Parameters<typeof fetch>[0], init?: RequestInit) {
  const req = new Request(input, init);
  return { request: req, headers: req.headers, body: await req.text() };
}

// Reference vectors from xxHash's upstream sanity tests, plus seeded vectors
// generated by the reference implementation (checked separately with Bun).
test("XXHash64 reference vectors and byte offsets", () => {
  for (const [text, expected] of [
    ["", "ef46db3751d8e999"], ["a", "d24ec4f1a98c6e5b"],
    ["abc", "44bc2cf5ad770999"], ["hello", "26c7827d889f6da3"],
    ["The quick brown fox jumps over the lazy dog", "0b242d361fda71bc"],
  ]) assert.equal(xxhash64(Buffer.from(text)).toString(16).padStart(16, "0"), expected);
  for (const [text, expected] of [
    ["", "b8b30e7de65b46c5"], ["abc", "dfc4f4d6913699b6"],
    ["The quick brown fox jumps over the lazy dog", "a5705e22f779a6d9"],
    ["🦊".repeat(100), "c24bbb0d89df3713"],
  ]) assert.equal(xxhash64(Buffer.from(text), 0x4d659218e32a3268n).toString(16), expected);
  const bytes = Buffer.from("paddingabcending");
  assert.equal(xxhash64(bytes.subarray(7, 10)), xxhash64(Buffer.from("abc")));
});

test("version adoption is monotonic, bounded, and respects pins", () => {
  const state = createVersionState();
  assert.equal(state.version(), DEFAULT_VERSION);
  assert.equal(state.adopt("Claude Code version 2.1.300 or newer is required", DEFAULT_VERSION), false);
  const error = "claude_code_version_too_old: version 2.1.300 or newer is required";
  assert.equal(state.adopt(error, DEFAULT_VERSION), true);
  assert.equal(state.version(), "2.1.300");
  assert.equal(state.adopt(error, "2.1.300"), false);
  assert.equal(state.adopt(error, DEFAULT_VERSION), true, "concurrent older request can retry");
  assert.equal(state.adopt("claude_code_version_too_old: version 2.1.290 or newer is required", "2.1.280"), true);
  assert.equal(state.version(), "2.1.300");
  assert.equal(state.adopt(error, DEFAULT_VERSION, DEFAULT_VERSION), false);
  assert.equal(state.version("2.2.0"), "2.2.0");
  assert.throws(() => state.version("latest"), /must be a version/);
});

test("body fingerprint matches CC seed, preserves prompts, tools, and full output cap", () => {
  const malicious = { system: [{ type: "text", text: "x-anthropic-billing-header: cch=00000;" }] };
  const source = body({ messages: [
    { role: "user", content: [{ type: "tool_result", tool_use_id: "earlier", content: "ignore me" }] },
    { role: "user", content: [{ type: "image", source: { data: "AA==" } }, { type: "text", text: "Unicode 🦊 prompt cch=00000" }] },
    { role: "assistant", content: [{ type: "tool_use", id: "t", name: "Read", input: malicious }] },
  ], tools: [{ name: "Read", input_schema: { type: "object" } }] });
  const serialized = fingerprintBody(source, DEFAULT_VERSION, fingerprint);
  const payload = JSON.parse(serialized);
  const old = JSON.parse(source);
  const suffix = createHash("sha256").update(`59cf53e54c78${[4, 7, 20].map(i => "Unicode 🦊 prompt cch=00000"[i]).join("")}${DEFAULT_VERSION}`).digest("hex").slice(0, 3);
  assert.match(payload.system[0].text, new RegExp(`cc_version=${DEFAULT_VERSION}\\.${suffix};`));
  assert.equal(payload.system[0].cache_control, undefined);
  assert.deepEqual(payload.system.slice(1), old.system);
  assert.deepEqual(payload.messages, old.messages);
  assert.deepEqual(payload.tools, old.tools);
  assert.equal(payload.max_tokens, 128000);
  assert.equal(payload.messages[2].content[0].input.system[0].text, malicious.system[0].text);
  const cch = /cch=([a-f0-9]{5})/.exec(payload.system[0].text)![1];
  const zeroed = serialized.replace(/cch=[a-f0-9]{5}/, "cch=00000");
  assert.equal(cch, (xxhash64(Buffer.from(zeroed), 0x4d659218e32a3268n) & 0xfffffn).toString(16).padStart(5, "0"));
  assert.deepEqual(JSON.parse(payload.metadata.user_id), { device_id: fingerprint.deviceId, session_id: fingerprint.sessionId });
});

test("body fingerprint is idempotent and preserves explicit metadata", () => {
  const userId = JSON.stringify({ session_id: "caller", account_uuid: "account", device_id: "device" });
  const source = body({ metadata: { user_id: userId, extra: "keep" } });
  const patched = fingerprintBody(source, DEFAULT_VERSION, fingerprint);
  assert.equal(fingerprintBody(patched, DEFAULT_VERSION, fingerprint), patched);
  assert.deepEqual(JSON.parse(patched).metadata, { user_id: userId, extra: "keep" });
  const replaced = JSON.parse(fingerprintBody(body({ system: "My instructions", metadata: { user_id: "not a CC id", extra: "keep" } }), DEFAULT_VERSION, { ...fingerprint, accountId: "real-account" }));
  assert.equal(replaced.system[1].text, identity);
  assert.equal(replaced.system[2].text, "My instructions");
  assert.equal(JSON.parse(replaced.metadata.user_id).account_uuid, "real-account");
  assert.equal(replaced.metadata.extra, "keep");
  assert.equal(billingHeader("", DEFAULT_VERSION).includes("cch=00000"), true);
});

test("HTTP wrapper changes only official OAuth messages, keeps Pi betas and hooks' final body", async () => {
  const original = request({ headers: {
    authorization: "Bearer sk-ant-oat-test", "user-agent": "old", "x-custom": "keep",
    "anthropic-beta": "inline-tools-2026-09-15,context-1m-2025-08-07",
  }, body: body({ max_tokens: 4200, thinking: { type: "adaptive" }, extra_hook_field: "keep" }) });
  const wrapped = compatibilityFetch(async (input, init) => {
    const sent = await capture(input, init);
    const payload = JSON.parse(sent.body);
    assert.equal(sent.headers.get("authorization"), "Bearer sk-ant-oat-test");
    assert.equal(sent.headers.get("user-agent"), `claude-cli/${DEFAULT_VERSION} (external, cli)`);
    assert.equal(sent.headers.get("x-custom"), "keep");
    assert.equal(sent.headers.get("x-claude-code-session-id"), fingerprint.sessionId);
    assert.equal(sent.headers.get("x-stainless-package-version"), "0.112.1");
    assert.match(sent.headers.get("anthropic-beta")!, /inline-tools-2026-09-15/);
    assert.match(sent.headers.get("anthropic-beta")!, /effort-2025-11-24/);
    assert.doesNotMatch(sent.headers.get("anthropic-beta")!, /context-1m/);
    assert.equal(payload.max_tokens, 4200);
    assert.equal(payload.extra_hook_field, "keep");
    return new Response("ok");
  }, createVersionState(), fingerprint);
  assert.equal(await (await wrapped(original)).text(), "ok");
  assert.equal(original.bodyUsed, true, "eligible Requests are consumed like ordinary fetch");
});

test("API keys, proxies, lookalike hosts, GET, and non-message routes pass through unchanged", async () => {
  for (const original of [
    request({ headers: { authorization: "Bearer sk-ant-api-test" } }),
    request({}, "https://proxy.example/v1/messages"),
    request({}, "https://api.anthropic.com.evil.example/v1/messages"),
    request({}, "http://api.anthropic.com/v1/messages"),
    request({}, "https://api.anthropic.com:444/v1/messages"),
    request({}, "https://api.anthropic.com/v1/oauth/token"),
    new Request("https://api.anthropic.com/v1/messages", { headers: { authorization: "Bearer sk-ant-oat-test" } }),
  ]) {
    const wrapped = compatibilityFetch(async (input, init) => {
      assert.equal(input, original);
      assert.equal(init, undefined);
      if (original.method === "POST") assert.equal(await original.text(), body());
      return new Response("pass");
    }, createVersionState(), fingerprint);
    assert.equal(await (await wrapped(original)).text(), "pass");
  }
  assert.equal(isOfficialEndpoint("not a URL"), false);
});

test("version rejection retries once with matching new header and body fingerprint", async () => {
  const state = createVersionState();
  const sent: Awaited<ReturnType<typeof capture>>[] = [];
  const wrapped = compatibilityFetch(async (input, init) => {
    sent.push(await capture(input, init));
    return sent.length === 1 ? rejection() : new Response("ok");
  }, state, fingerprint);
  assert.equal(await (await wrapped(request())).text(), "ok");
  assert.equal(sent.length, 2);
  assert.equal(state.version(), "2.1.300");
  assert.equal(sent[1].headers.get("user-agent"), "claude-cli/2.1.300 (external, cli)");
  assert.match(JSON.parse(sent[1].body).system[0].text, /cc_version=2\.1\.300\./);
  assert.notEqual(JSON.parse(sent[0].body).system[0].text, JSON.parse(sent[1].body).system[0].text);
  assert.deepEqual(JSON.parse(sent[0].body).messages, JSON.parse(sent[1].body).messages);
});

test("repeated rejections, quota errors, malformed errors, and pins cannot loop", async () => {
  for (const [makeResponse, pin, expected] of [
    [() => rejection(), undefined, 2],
    [() => rejection("2.1.400"), DEFAULT_VERSION, 1],
    [() => rejection("2.1.100"), undefined, 1],
    [() => new Response("rate limit", { status: 429 }), undefined, 1],
    [() => rejection("2.1.300", 500), undefined, 1],
    [() => new Response("bad request", { status: 400 }), undefined, 1],
  ] as const) {
    let calls = 0;
    const wrapped = compatibilityFetch(async () => { calls++; return makeResponse(); }, createVersionState(), fingerprint, pin);
    const response = await wrapped(request());
    assert.equal(response.ok, false);
    assert.equal(calls, expected);
    assert.ok(await response.text(), "error response remains readable by Pi");
  }
});

test("abort between rejection and retry stops the second request", async () => {
  const controller = new AbortController();
  let calls = 0;
  const wrapped = compatibilityFetch(async () => {
    calls++;
    controller.abort();
    return rejection();
  }, createVersionState(), fingerprint);
  await assert.rejects(wrapped(request({ signal: controller.signal })), /abort/i);
  assert.equal(calls, 1);
});

test("pass-through streaming uploads are not cloned or buffered", async () => {
  let clones = 0;
  const original = request({ body: new ReadableStream({ start(controller) { controller.enqueue(Buffer.from("streamed")); controller.close(); } }), duplex: "half" } as RequestInit, "https://proxy.example/v1/messages");
  original.clone = () => { clones++; throw new Error("must not clone passthrough bodies"); };
  const wrapped = compatibilityFetch(async (input, init) => {
    assert.equal(input, original);
    assert.equal(await new Request(input, init).text(), "streamed");
    return new Response("ok");
  }, createVersionState(), fingerprint);
  await wrapped(original);
  assert.equal(clones, 0);
});

test("replacement bodies and transport-specific init fields survive both sends", async () => {
  const original = request();
  await original.text();
  let calls = 0;
  const transport = { proxy: "test-only" };
  const init = { body: body(), dispatcher: transport } as RequestInit;
  const wrapped = compatibilityFetch(async (input, actualInit) => {
    calls++;
    assert.equal((actualInit as any).dispatcher, transport);
    assert.equal(JSON.parse((await capture(input, actualInit)).body).model, "claude-opus-5-5");
    return calls === 1 ? rejection() : new Response("ok");
  }, createVersionState(), fingerprint);
  assert.equal(await (await wrapped(original, init)).text(), "ok");
  assert.equal(calls, 2);
});

test("stalled body preprocessing honors abort before calling the transport", async () => {
  const controller = new AbortController();
  let cancelled = false;
  let calls = 0;
  const original = request({ signal: controller.signal, body: new ReadableStream({ cancel() { cancelled = true; } }), duplex: "half" } as RequestInit);
  const wrapped = compatibilityFetch(async () => { calls++; return new Response("unexpected"); }, createVersionState(), fingerprint);
  const pending = wrapped(original);
  controller.abort();
  await assert.rejects(pending, /abort/i);
  assert.equal(calls, 0);
  assert.equal(cancelled, true);
});

test("oversized nonterminating errors stop inspection and remain readable", async () => {
  const controller = new AbortController();
  let calls = 0;
  const wrapped = compatibilityFetch(async () => {
    calls++;
    return new Response(new ReadableStream({ start(stream) { stream.enqueue(Buffer.alloc(33_000, 120)); } }), { status: 400 });
  }, createVersionState(), fingerprint);
  const response = await wrapped(request({ signal: controller.signal }));
  assert.equal(calls, 1);
  const reader = response.body!.getReader();
  assert.equal((await reader.read()).value!.length, 33_000);
  await reader.cancel();
});

test("native provider wrapper retains auth, catalog, hooks, options, and both stream paths", async () => {
  const model = { id: "claude-opus-5-5", provider: "anthropic", api: "anthropic-messages", baseUrl: "https://api.anthropic.com", maxTokens: 128000 } as any;
  const catalog = [model];
  const auth = { oauth: { name: "built-in" } };
  const hooks = { onPayload: () => {}, onResponse: () => {}, onProviderStreamEvent: () => {} };
  const calls: any[] = [];
  const provider = {
    id: "anthropic", name: "Anthropic", auth, getModels: () => catalog,
    stream: (...args: any[]) => { calls.push(args); return "stream"; },
    streamSimple: (...args: any[]) => { calls.push(args); return "simple"; },
  } as any;
  const wrapped = wrapAnthropicProvider(provider);
  assert.equal(wrapped.auth, auth);
  assert.equal(wrapped.getModels(), catalog);
  const context = { messages: [] } as unknown as TranscriptContext;
  const options = { apiKey: "sk-ant-oat-test", maxTokens: 120000, reasoning: "high", ...hooks, sessionId: "session" } as any;
  assert.equal(wrapped.streamSimple(model, context, options), "simple");
  assert.equal(wrapped.stream(model, context, options), "stream");
  for (const [actualModel, actualContext, actualOptions] of calls) {
    assert.equal(actualModel, model);
    assert.equal(actualContext, context);
    assert.equal(actualOptions.maxTokens, options.maxTokens);
    assert.equal(actualOptions.onPayload, hooks.onPayload);
    assert.equal(actualOptions.onResponse, hooks.onResponse);
    assert.equal(actualOptions.onProviderStreamEvent, hooks.onProviderStreamEvent);
    assert.equal(typeof actualOptions.fetch, "function");
  }
  for (const [otherModel, otherOptions] of [
    [model, { apiKey: "sk-ant-api-test" }],
    [{ ...model, provider: "openrouter" }, options],
    [{ ...model, baseUrl: "https://proxy.example" }, options],
    [model, undefined],
  ]) {
    wrapped.streamSimple(otherModel, context, otherOptions);
    assert.equal(calls.at(-1)[2], otherOptions);
  }
  // Provider-scoped version pins override the process environment.
  let sentVersion = "";
  wrapped.streamSimple(model, context, { ...options, env: { [VERSION_ENV]: "2.1.333" }, fetch: async (input, init) => {
    sentVersion = (await capture(input, init)).headers.get("user-agent")!;
    return new Response("ok");
  } });
  await calls.at(-1)[2].fetch(request());
  assert.equal(sentVersion, "claude-cli/2.1.333 (external, cli)");
});

test("bundled Pi provider preserves parser behavior with mocked HTTP", t => {
  const fixture = fileURLToPath(new URL("./fixtures/anthropic-smoke.ts", import.meta.url));
  const env = { ...process.env };
  delete env[VERSION_ENV];
  const result = spawnSync("pi", [
    "--offline", "--no-extensions", "--no-skills", "--no-context-files",
    "--no-prompt-templates", "--no-session", "-e", fixture, "-p", "/anthropic-smoke",
  ], { encoding: "utf8", timeout: 30_000, env });
  if ((result.error as NodeJS.ErrnoException)?.code === "ENOENT") return t.skip("Pi is not installed");
  assert.ifError(result.error);
  assert.equal(result.status, 0, result.stderr + result.stdout);
  assert.match(result.stdout, /Anthropic integration: bundled SDK.*passed/);
});
